import fs from 'fs/promises';
import path from 'path';

// pptxgenjs is commonjs
// eslint-disable-next-line @typescript-eslint/no-var-requires
const pptxgen = require('pptxgenjs');

export type FilledSlide = {
    id: string;
    name?: string;
    content: Record<string, any>;
};

const getPublicBaseUrl = () => process.env.PUBLIC_BASE_URL || `http://localhost:${process.env.PORT || 5000}`;

const ensureDir = async (dirPath: string) => {
    await fs.mkdir(dirPath, { recursive: true });
};

const normalizeText = (value: any): string => {
    if (value === null || value === undefined) return '';
    if (typeof value === 'string') return value;
    if (Array.isArray(value)) return value.map((v) => normalizeText(v)).filter(Boolean).join('\n');
    if (typeof value === 'object') return JSON.stringify(value);
    return String(value);
};

export const exportFilledTemplateToPptx = async (opts: {
    templateName: string;
    templateId: string;
    slides: FilledSlide[];
}) => {
    const pptx = new pptxgen();
    pptx.layout = 'LAYOUT_WIDE';

    // simple theme-ish defaults
    pptx.author = 'NextIgnition';
    pptx.company = 'NextIgnition';
    pptx.subject = opts.templateName;

    for (const slideData of opts.slides) {
        const slide = pptx.addSlide();

        // Title
        slide.addText(slideData.name || 'Slide', {
            x: 0.5,
            y: 0.3,
            w: 12.3,
            h: 0.6,
            fontSize: 28,
            bold: true,
            color: '1F2937',
        });

        const fields = Object.entries(slideData.content || {});
        const bodyLines = fields.map(([k, v]) => `${k}: ${normalizeText(v)}`).join('\n\n');

        slide.addText(bodyLines || 'No content', {
            x: 0.7,
            y: 1.2,
            w: 12.0,
            h: 5.6,
            fontSize: 16,
            color: '111827',
            valign: 'top',
        });

        // Footer
        slide.addText('Generated by Ignisha AI • nextignition.com', {
            x: 0.5,
            y: 6.9,
            w: 12.3,
            h: 0.4,
            fontSize: 10,
            color: '6B7280',
        });
    }

    const safeBaseName = `${opts.templateId}-${Date.now()}`.replace(/[^a-zA-Z0-9-_]/g, '_');
    const fileName = `${safeBaseName}.pptx`;

    const uploadsRoot = path.join(__dirname, '..', '..', 'uploads');
    const outDir = path.join(uploadsRoot, 'templates');
    await ensureDir(outDir);

    const outPath = path.join(outDir, fileName);

    // writeFile returns a Promise in pptxgenjs
    await pptx.writeFile({ fileName: outPath });

    const baseUrl = getPublicBaseUrl();
    const downloadUrl = `${baseUrl}/uploads/templates/${fileName}`;

    return { fileName, outPath, downloadUrl };
};
