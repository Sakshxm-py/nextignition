import React, { useState, useEffect } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { 
  X, 
  Download, 
  Loader2, 
  Sparkles, 
  Shield, 
  TrendingUp, 
  AlertTriangle, 
  CheckCircle2, 
  PieChart,
  FileText,
  ChevronRight
} from 'lucide-react';
import { jsPDF } from 'jspdf';
import { generatePortfolioAnalysis } from '../services/aiService';
import { brandColors } from '../utils/colors';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';

type PortfolioAnalysis = {
  summary: string;
  metrics: {
    totalInvested: string;
    diversityScore: number;
    riskLevel: string;
  };
  sectorAnalysis: Array<{ sector: string; percentage: number; outlook: string }>;
  riskAssessment: Array<{ startup: string; risk: string; mitigation: string }>;
  recommendations: Array<{ title: string; description: string; priority: string }>;
  fullReport: string;
};

type AIPortfolioAnalysisModalProps = {
  isOpen: boolean;
  onClose: () => void;
  portfolioStartups: any[];
};

export function AIPortfolioAnalysisModal({ isOpen, onClose, portfolioStartups }: AIPortfolioAnalysisModalProps) {
  const [analysis, setAnalysis] = useState<PortfolioAnalysis | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (isOpen && !analysis && portfolioStartups.length > 0) {
      handleGenerate();
    }
  }, [isOpen, portfolioStartups]);

  const handleGenerate = async () => {
    setLoading(true);
    setError(null);
    try {
      const data = await generatePortfolioAnalysis(portfolioStartups);
      setAnalysis(data);
    } catch (err) {
      console.error('Failed to generate analysis:', err);
      setError('Failed to generate portfolio analysis. Please try again.');
    } finally {
      setLoading(false);
    }
  };

  const handleDownloadPDF = () => {
    if (!analysis) return;

    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();
    let y = 20;

    // Title
    doc.setFontSize(22);
    doc.setTextColor(102, 102, 255); // #6666ff
    doc.text('Portfolio Health Report', 20, y);
    y += 10;

    doc.setFontSize(12);
    doc.setTextColor(100, 100, 100);
    doc.text(`Generated by Ignisha AI on ${new Date().toLocaleDateString()}`, 20, y);
    y += 15;

    // Summary
    doc.setFontSize(16);
    doc.setTextColor(0, 0, 0);
    doc.text('Executive Summary', 20, y);
    y += 10;
    doc.setFontSize(11);
    const splitSummary = doc.splitTextToSize(analysis.summary, pageWidth - 40);
    doc.text(splitSummary, 20, y);
    y += splitSummary.length * 7;

    // Metrics
    doc.setFontSize(16);
    doc.text('Key Metrics', 20, y);
    y += 10;
    doc.setFontSize(11);
    doc.text(`Total Invested: ${analysis.metrics.totalInvested}`, 25, y);
    y += 7;
    doc.text(`Diversity Score: ${analysis.metrics.diversityScore}/100`, 25, y);
    y += 7;
    doc.text(`Risk Level: ${analysis.metrics.riskLevel}`, 25, y);
    y += 15;

    // Recommendations
    if (y > 250) { doc.addPage(); y = 20; }
    doc.setFontSize(16);
    doc.text('Strategic Recommendations', 20, y);
    y += 10;
    analysis.recommendations.forEach((rec) => {
      if (y > 260) { doc.addPage(); y = 20; }
      doc.setFontSize(12);
      doc.setFont('helvetica', 'bold');
      doc.text(`• ${rec.title} (${rec.priority} Priority)`, 25, y);
      y += 6;
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      const splitDesc = doc.splitTextToSize(rec.description, pageWidth - 50);
      doc.text(splitDesc, 30, y);
      y += splitDesc.length * 5 + 5;
    });

    // Full Report
    doc.addPage();
    y = 20;
    doc.setFontSize(16);
    doc.text('Detailed Analysis', 20, y);
    y += 10;
    doc.setFontSize(10);
    const splitReport = doc.splitTextToSize(analysis.fullReport.replace(/[#*]/g, ''), pageWidth - 40);
    doc.text(splitReport, 20, y);

    doc.save(`Portfolio_Analysis_${new Date().toISOString().split('T')[0]}.pdf`);
  };

  if (!isOpen) return null;

  return (
    <AnimatePresence>
      <div className="fixed inset-0 z-[100] flex items-center justify-center p-4">
        <motion.div
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          exit={{ opacity: 0 }}
          onClick={onClose}
          className="absolute inset-0 bg-black/60 backdrop-blur-sm"
        />
        
        <motion.div
          initial={{ opacity: 0, scale: 0.95, y: 20 }}
          animate={{ opacity: 1, scale: 1, y: 0 }}
          exit={{ opacity: 0, scale: 0.95, y: 20 }}
          className="relative bg-white w-full max-w-4xl max-h-[90vh] rounded-3xl overflow-hidden shadow-2xl flex flex-col"
        >
          {/* Header */}
          <div className="px-8 py-6 border-b border-gray-100 flex items-center justify-between bg-gradient-to-r from-gray-50 to-white">
            <div className="flex items-center gap-3">
              <div className="w-10 h-10 bg-indigo-50 rounded-xl flex items-center justify-center text-indigo-600">
                <Sparkles className="w-6 h-6" />
              </div>
              <div>
                <h2 className="text-xl font-bold text-gray-900">Portfolio Health Analysis</h2>
                <p className="text-sm text-gray-500">Comprehensive AI Audit by Ignisha</p>
              </div>
            </div>
            <div className="flex items-center gap-2">
              {analysis && (
                <button
                  onClick={handleDownloadPDF}
                  className="flex items-center gap-2 px-4 py-2 bg-indigo-600 text-white rounded-xl text-sm font-bold hover:bg-indigo-700 transition-colors shadow-lg shadow-indigo-100"
                >
                  <Download className="w-4 h-4" />
                  Download PDF
                </button>
              )}
              <button 
                onClick={onClose}
                className="p-2 hover:bg-gray-100 rounded-full transition-colors"
              >
                <X className="w-6 h-6 text-gray-400" />
              </button>
            </div>
          </div>

          {/* Content */}
          <div className="flex-1 overflow-y-auto p-8 custom-scrollbar">
            {loading ? (
              <div className="h-64 flex flex-col items-center justify-center gap-4">
                <div className="relative">
                  <Loader2 className="w-12 h-12 text-indigo-600 animate-spin" />
                  <Sparkles className="w-4 h-4 text-amber-400 absolute -top-1 -right-1" />
                </div>
                <div className="text-center">
                  <p className="text-lg font-bold text-gray-900">Ignisha is auditing your portfolio...</p>
                  <p className="text-sm text-gray-500">Analyzing diversity, risk patterns, and market outlook</p>
                </div>
              </div>
            ) : error ? (
              <div className="p-12 text-center">
                <div className="w-16 h-16 bg-red-50 text-red-600 rounded-full flex items-center justify-center mx-auto mb-4">
                  <AlertTriangle className="w-8 h-8" />
                </div>
                <h3 className="text-lg font-bold text-gray-900 mb-2">Analysis Failed</h3>
                <p className="text-gray-500 mb-6">{error}</p>
                <button 
                  onClick={handleGenerate}
                  className="px-6 py-2 bg-indigo-600 text-white rounded-xl font-bold hover:bg-indigo-700 transition-colors"
                >
                  Retry Analysis
                </button>
              </div>
            ) : analysis ? (
              <div className="space-y-8">
                {/* Executive Summary */}
                <section className="bg-indigo-50/50 rounded-2xl p-6 border border-indigo-100">
                  <h3 className="text-sm font-bold text-indigo-900 uppercase tracking-wider mb-3 flex items-center gap-2">
                    <CheckCircle2 className="w-4 h-4" />
                    Executive Summary
                  </h3>
                  <p className="text-gray-700 leading-relaxed text-lg italic">
                    "{analysis.summary}"
                  </p>
                </section>

                {/* Key Metrics Grid */}
                <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
                  <div className="p-6 bg-white rounded-2xl border border-gray-100 shadow-sm flex items-center gap-4">
                    <div className="w-12 h-12 bg-green-50 text-green-600 rounded-xl flex items-center justify-center">
                      <TrendingUp className="w-6 h-6" />
                    </div>
                    <div>
                      <p className="text-xs text-gray-500 uppercase font-bold">Invested</p>
                      <p className="text-xl font-bold text-gray-900">{analysis.metrics.totalInvested}</p>
                    </div>
                  </div>
                  <div className="p-6 bg-white rounded-2xl border border-gray-100 shadow-sm flex items-center gap-4">
                    <div className="w-12 h-12 bg-blue-50 text-blue-600 rounded-xl flex items-center justify-center">
                      <PieChart className="w-6 h-6" />
                    </div>
                    <div>
                      <p className="text-xs text-gray-500 uppercase font-bold">Diversity</p>
                      <p className="text-xl font-bold text-gray-900">{analysis.metrics.diversityScore}/100</p>
                    </div>
                  </div>
                  <div className="p-6 bg-white rounded-2xl border border-gray-100 shadow-sm flex items-center gap-4">
                    <div className={`w-12 h-12 rounded-xl flex items-center justify-center ${
                      analysis.metrics.riskLevel === 'Low' ? 'bg-green-50 text-green-600' :
                      analysis.metrics.riskLevel === 'Medium' ? 'bg-amber-50 text-amber-600' :
                      'bg-red-50 text-red-600'
                    }`}>
                      <Shield className="w-6 h-6" />
                    </div>
                    <div>
                      <p className="text-xs text-gray-500 uppercase font-bold">Risk Level</p>
                      <p className="text-xl font-bold text-gray-900">{analysis.metrics.riskLevel}</p>
                    </div>
                  </div>
                </div>

                <div className="grid grid-cols-1 lg:grid-cols-2 gap-8">
                  {/* Sector Analysis */}
                  <div>
                    <h3 className="text-lg font-bold text-gray-900 mb-4 flex items-center gap-2">
                      <PieChart className="w-5 h-5 text-indigo-600" />
                      Sector Exposure
                    </h3>
                    <div className="bg-gray-50 rounded-2xl p-6 space-y-4">
                      {analysis.sectorAnalysis.map((sector, i) => (
                        <div key={i} className="space-y-2">
                          <div className="flex justify-between text-sm">
                            <span className="font-bold text-gray-700">{sector.sector}</span>
                            <span className="text-gray-500">{sector.percentage}%</span>
                          </div>
                          <div className="h-2 bg-gray-200 rounded-full overflow-hidden">
                            <motion.div 
                              initial={{ width: 0 }}
                              animate={{ width: `${sector.percentage}%` }}
                              className="h-full bg-indigo-500"
                            />
                          </div>
                          <p className="text-xs text-gray-500 italic">Outlook: {sector.outlook}</p>
                        </div>
                      ))}
                    </div>
                  </div>

                  {/* Recommendations */}
                  <div>
                    <h3 className="text-lg font-bold text-gray-900 mb-4 flex items-center gap-2">
                      <Sparkles className="w-5 h-5 text-indigo-600" />
                      Strategic Advice
                    </h3>
                    <div className="space-y-3">
                      {analysis.recommendations.map((rec, i) => (
                        <div key={i} className="p-4 bg-white border border-gray-100 rounded-xl shadow-sm hover:shadow-md transition-shadow">
                          <div className="flex items-center justify-between mb-1">
                            <h4 className="font-bold text-sm text-gray-900">{rec.title}</h4>
                            <span className={`text-[10px] px-2 py-0.5 rounded-full font-bold uppercase ${
                              rec.priority === 'High' ? 'bg-red-50 text-red-600' :
                              rec.priority === 'Medium' ? 'bg-amber-50 text-amber-600' :
                              'bg-green-50 text-green-600'
                            }`}>
                              {rec.priority}
                            </span>
                          </div>
                          <p className="text-xs text-gray-500 leading-relaxed">{rec.description}</p>
                        </div>
                      ))}
                    </div>
                  </div>
                </div>

                {/* Risk Assessment */}
                <section>
                  <h3 className="text-lg font-bold text-gray-900 mb-4 flex items-center gap-2">
                    <Shield className="w-5 h-5 text-indigo-600" />
                    Specific Risk Assessment
                  </h3>
                  <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                    {analysis.riskAssessment.map((risk, i) => (
                      <div key={i} className="p-4 bg-orange-50/30 border border-orange-100 rounded-xl">
                        <div className="flex items-center gap-2 mb-2">
                          <AlertTriangle className="w-4 h-4 text-orange-600" />
                          <h4 className="font-bold text-sm text-gray-900">{risk.startup}</h4>
                        </div>
                        <p className="text-xs text-gray-700 font-medium mb-1">Risk: {risk.risk}</p>
                        <p className="text-xs text-indigo-600">Mitigation: {risk.mitigation}</p>
                      </div>
                    ))}
                  </div>
                </section>

                {/* Full Report Markdown */}
                <section className="border-t border-gray-100 pt-8">
                  <h3 className="text-lg font-bold text-gray-900 mb-6 flex items-center gap-2">
                    <FileText className="w-5 h-5 text-indigo-600" />
                    Detailed Intelligence Report
                  </h3>
                  <div className="prose prose-indigo prose-sm max-w-none text-gray-600 bg-white p-8 rounded-3xl border border-gray-100 shadow-sm leading-relaxed">
                    <ReactMarkdown remarkPlugins={[remarkGfm]}>
                      {analysis.fullReport}
                    </ReactMarkdown>
                  </div>
                </section>
              </div>
            ) : (
              <div className="h-64 flex items-center justify-center text-gray-500">
                No portfolio data available to analyze.
              </div>
            )}
          </div>

          {/* Footer */}
          <div className="px-8 py-4 bg-gray-50 border-t border-gray-100 flex items-center justify-between">
            <p className="text-[10px] text-gray-400 font-medium tracking-tight">
              PROPRIETARY ANALYSIS BY IGNISHA AI • CONFIDENTIAL TO INVESTOR 
            </p>
            <div className="flex gap-4">
              <button 
                onClick={onClose}
                className="px-6 py-2 text-gray-600 font-bold hover:bg-gray-100 rounded-xl transition-colors"
              >
                Close Report
              </button>
              {analysis && (
                <button
                  onClick={handleDownloadPDF}
                  className="px-6 py-2 bg-indigo-600 text-white rounded-xl font-bold hover:bg-indigo-700 transition-colors"
                >
                  Download Report
                </button>
              )}
            </div>
          </div>
        </motion.div>
      </div>
    </AnimatePresence>
  );
}
